/** {0},{1}… 자리에 숫자를 순서대로 채운다 */
function fill(tpl, nums) {
  return tpl.replace(/\{(\d+)\}/g, (_, k) => {
    const v = nums[Number(k)];
    return v == null ? '' : String(v);
  });
}

/* 순수 수식이거나 숫자 없는 문제는 상황 문장으로 바꾸지 않는다.
 *
 * ★ 결함 두 번을 겪고 나서야 알았다 (기록해 둔다):
 *   1) "숫자 0개면 건너뛰기" — m_compare10("가장 큰 수는 무엇일까?") 를
 *      "토끼가 을 달렸고" 처럼 빈자리 문장으로 바꾸는 것을 막았다. 이건 맞다.
 *   2) 그다음 "숫자와 기호로만 이루어진 질문이면 건너뛰기" 를 넣었다가
 *      m_add10("2 + 3 = ?")·m_sub10·m_add_carry1 이 전부 원본으로 돌아가고
 *      상황변형 효과가 0 이었다(시그니처 1종 고정).
 *      → 두 자리 계산은 상황 문장에 넣어도 뜻이 통한다. 이 조건은 뺀다.
 *
 * 남기는 조건은 딱 두 개다:
 *   · 숫자가 하나도 없다 → 문장이 깨진다
 *   · 값이 세 자리 이상이다 → "88 + 5" 를 사과 가방에 넣으면 뜻이 통하지 않는다
 */
const TOOBIG = (nums) => nums.some((n) => String(n).length >= 3);

/**
 * 생성기 하나를 '상황 변형 가능'한 함수로 감싼다.
 * 원본 gen( story ) 이 만든 정답·보기·오답설명은 그대로 두고,
 * 질문문만 상황 문장으로 바꿔 넣는다. → signature() 이 서로 다른 걸 잡는다.
 */
export function vary(gen, skillId) {
  const tpls = S[skillId];
  if (!tpls) return gen;

  return function (story) {
    const it = gen(story);
    if (!it || !it.q) return it;

    const raw = String(it.q);

    const nums = (raw.match(/\d+/g) || []).map(Number);

    // ① 숫자가 없으면 문장이 깨진다. 값이 세 자리 이상이면 뜻이 통하지 않는다.
    if (!nums.length) return it;
    if (TOOBIG(nums)) return it;

    // ② 원본의 숫자 개수와 맞는 템플릿만 고른다 (빈 자리 방지)
    const fits = tpls.filter((t) => (t.match(/\{\d+\}/g) || []).length === nums.length);
    if (!fits.length) return it;

    const tpl = fits[Math.floor(Math.random() * fits.length)];
    const q = fill(tpl, nums);

    // ③ 해설(why)에도 같은 숫자를 순서대로 넣어 앞뒤가 어긋나지 않게 한다
    let why = it.why;
    if (why && nums.length) {
      let i = 0;
      why = String(why).replace(/\d+/g, (m) => (i < nums.length ? String(nums[i++]) : m));
    }

    return { ...it, q, why };
  };
}

