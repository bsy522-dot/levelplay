/* ── 숫자 없이 다시 묻는 문장 세기 ── */
const fill = (tpl, nums) => tpl.replace(/\{(\d+)\}/g, (_, k) => {
  const v = nums[Number(k)];
  return v == null ? '' : String(v);
});

/* 값이 세 자리 이상이면 상황 문장에 넣어도 뜻이 통하지 않는다 — 이건 그대로 둔다.
 * 실측 근거: "88 + 5 = ?" 를 사과 가방에 넣으면 88개 사과가 이상하다.
 * 다만 507 + 235(세 자리 덧셈)처럼 원본이 이미 수식인 경우도 있어,
 * 그쪽은 FRAME 로 '무엇을 묻는가'를 바꾼다. */
const TOOBIG = (nums) => nums.some((n) => String(n).length >= 3);

/**
 * 생성기를 '상황 변형 가능'한 함수로 감싼다.
 * 원본 gen( story ) 이 만든 정답·보기·오답설명은 그대로 두고,
 * 질문문만 다른 방식으로 바꾼다. → signature() 이 서로 다른 걸 잡는다.
 */
export function vary(gen, skillId) {
  const nums0 = NUM[skillId];
  const frames = FRAME[skillId];
  if (!nums0 && !frames) return gen;

  return function (story) {
    const it = gen(story);
    if (!it || !it.q) return it;

    const raw = String(it.q);
    /* 소수까지 한 덩어리로 뽑는다.
     * 실측 결함: "0.8 + 0.5 = ?" 에서 /\d+/g 는 '0','8','0','5' 네 개로 쪼갠다.
     *   그래서 소수 문장 템플릿(4자리)이 안 맞아 통째로 원본이 돌아갔고,
     *   m_dec_add 가 시그니처 1종으로 남았다.
     *   → 마침표로 이어진 숫자를 하나로 본다. */
    const nums = (raw.match(/\d+(?:[.]\d+)?/g) || []).map(Number);

    // ── ① 숫자가 있다 → 숫자 개수와 맞는 상황 문장을 고른다
    if (nums.length && nums0 && !TOOBIG(nums)) {
      const fits = nums0.filter((t) => (t.match(/\{\d+\}/g) || []).length === nums.length);
      if (fits.length) {
        const tpl = fits[Math.floor(Math.random() * fits.length)];
        // 해설(why)에도 같은 숫자를 순서대로 넣어 앞뒤가 어긋나지 않게 한다
        let why = it.why;
        if (why && nums.length) {
          let i = 0;
          why = String(why).replace(/\d+/g, (m) => (i < nums.length ? String(nums[i++]) : m));
        }
        return { ...it, q: fill(tpl, nums), why };
      }
    }

    // ── ② 숫자가 없거나 숫자 문장을 쓸 수 없으면, '무엇을 묻는가'를 바꾼다
    if (frames && frames.length) {
      const tpl = frames[Math.floor(Math.random() * frames.length)];
      return { ...it, q: tpl };
    }

    return it;
  };
}

